const locale = ref<Locale>((localStorage.getItem('ecommerce_locale') as Locale) || 'en')

function setLocale(l: Locale) {
  locale.value = l
  localStorage.setItem('ecommerce_locale', l)
}

function t(key: string, params?: Record<string, string | number>): string {
  const template = dictionaries[locale.value][key] ?? dictionaries.en[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] !== undefined ? String(params[name]) : `{${name}}`,
  )
}

export { t }

function toggleLocale() {
  setLocale(locale.value === 'en' ? 'km' : 'en')
}

export function useI18n() {
  return { locale, setLocale, toggleLocale, t }
}

